"""
Generate a SYNTHETIC dataset for a short-term flood forecasting task.

NOTE: The data generated by this script is simulated for academic purposes and
is NOT real observational data from Ho Chi Minh City.

Goal: predict the water level 30 minutes ahead (6 steps x 5 minutes) from
current and historical values.

Run:
    python generate_flood_dataset.py

Dependencies: numpy, pandas, scikit-learn
"""

from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error

# ----------------------------- Configuration -----------------------------
RANDOM_SEED = 42
N_ROWS = 2000          # final number of rows after feature creation
HORIZON = 6            # 30 minutes = 6 steps
WARMUP = 11            # need 12 samples (11 prior + current) for the 60-min window
N_RAW = N_ROWS + WARMUP + HORIZON

rng = np.random.default_rng(RANDOM_SEED)
timestamps = pd.date_range("2026-09-01 00:00", periods=N_RAW, freq="5min")

# --------------------- 1. Generate rainfall events ------------------------
# Rainfall is generated in events, with dry periods between them.
rainfall = np.zeros(N_RAW)
i = 0
while i < N_RAW:
    if rng.random() < 0.035:  # probability of starting a rainfall event
        duration = int(rng.integers(6, 31))       # 30 minutes to 2.5 hours
        peak_mm_h = float(rng.uniform(6, 32))     # peak intensity (mm/hour)
        profile = 0.35 + np.sin(np.linspace(0, np.pi, duration))
        intensity = peak_mm_h * profile * rng.uniform(0.75, 1.15, duration)

        # mm/hour -> mm during one 5-minute step
        rainfall[i:i + duration] = intensity * 5 / 60
        i += duration + int(rng.integers(12, 49))  # dry period
    else:
        i += 1

rainfall = np.clip(rainfall, 0, None)  # ensure no negative rainfall

# --------------------- 2. Simulated tide level ----------------------------
steps = np.arange(N_RAW)
tide = (
    55
    + 22 * np.sin(2 * np.pi * steps / (12.4 * 12) + 0.8)
    + 3 * np.sin(2 * np.pi * steps / (24 * 12))
    + rng.normal(0, 0.6, N_RAW)
)
tide = np.clip(tide, 25, 85)

# ------------- 3. Drainage status (simple Markov chain) -------------------
# "restricted" is more likely during rain or high tide and tends to persist.
restricted = np.zeros(N_RAW, dtype=bool)
is_restricted = False
for t in range(N_RAW):
    if is_restricted:
        p_stay = 0.93 if rainfall[t] > 0 else 0.78
        is_restricted = rng.random() < p_stay
    else:
        p_enter = 0.012 + 0.05 * (rainfall[t] > 0) + 0.04 * (tide[t] > 65)
        is_restricted = rng.random() < p_enter
    restricted[t] = is_restricted

# --------------------- 4. Water level over time ---------------------------
# Water rises with rainfall and gradually recedes when drainage is favorable.
# Restricted drainage and high tide slow down the recession.
BASE_LEVEL = 35.0
water_level = np.empty(N_RAW)
water_level[0] = 50.0

for t in range(1, N_RAW):
    inflow = 1.15 * rainfall[t] + 0.25 * rainfall[t - 1]
    tide_effect = 0.010 * max(tide[t] - 60, 0)

    drainage_rate = 0.018 if restricted[t] else 0.055
    if tide[t] > 60:
        drainage_rate *= max(0.35, 1 - 0.035 * (tide[t] - 60))

    outflow = drainage_rate * max(water_level[t - 1] - BASE_LEVEL, 0)
    noise = rng.normal(0, 0.12)

    water_level[t] = (
        water_level[t - 1] + inflow + tide_effect - outflow + noise
    )
    water_level[t] = np.clip(water_level[t], 28, 100)

# ------------------------- 5. Build DataFrame -----------------------------
df = pd.DataFrame({
    "timestamp": timestamps,
    "water_level_cm": water_level,
    "rainfall_mm_5m": rainfall,
    "tide_level_cm": tide,
    "drainage_status": np.where(restricted, "restricted", "normal"),
})

# Lag features: use only current and past values.
df["water_level_lag_5m"] = df["water_level_cm"].shift(1)
df["water_level_lag_15m"] = df["water_level_cm"].shift(3)
df["water_level_lag_30m"] = df["water_level_cm"].shift(6)
df["water_level_change_5m"] = df["water_level_cm"] - df["water_level_lag_5m"]

# Total rainfall over the last 15 and 60 minutes (including the current step).
df["rainfall_mm_15m"] = df["rainfall_mm_5m"].rolling(3, min_periods=3).sum()
df["rainfall_mm_60m"] = df["rainfall_mm_5m"].rolling(12, min_periods=12).sum()

# Target: water level exactly 30 minutes later (6 steps).
df["water_level_future_30m"] = df["water_level_cm"].shift(-HORIZON)

# Drop rows with missing features/target due to warm-up and the final 30 minutes.
df = df.dropna().reset_index(drop=True)

# Order columns as specified.
df = df[[
    "timestamp",
    "water_level_cm",
    "water_level_lag_5m",
    "water_level_lag_15m",
    "water_level_lag_30m",
    "water_level_change_5m",
    "rainfall_mm_5m",
    "rainfall_mm_15m",
    "rainfall_mm_60m",
    "tide_level_cm",
    "drainage_status",
    "water_level_future_30m",
]]

assert len(df) == N_ROWS
assert (df["rainfall_mm_5m"] >= 0).all()
assert (df["rainfall_mm_15m"] >= 0).all()
assert (df["rainfall_mm_60m"] >= 0).all()

output_path = Path(__file__).with_name("flood_dataset.csv")
df.to_csv(output_path, index=False, float_format="%.3f")

# ------------------------- 6. Inspect the data ----------------------------
print("=" * 70)
print("DỮ LIỆU TỔNG HỢP - KHÔNG PHẢI DỮ LIỆU QUAN TRẮC THỰC TẾ")
print("=" * 70)
print(f"Đã lưu: {output_path}  ({len(df)} dòng)")
print("\n5 dòng đầu:")
print(df.head().to_string(index=False))

print("\nThống kê cơ bản:")
print(df.drop(columns=["timestamp", "drainage_status"])
        .describe().T.round(2).to_string())

print("\nPhân bố trạng thái thoát nước:")
print(df["drainage_status"].value_counts().to_string())

# --------------------- 7. Chronological train/test split ------------------
feature_cols = [
    "water_level_cm",
    "water_level_lag_5m",
    "water_level_lag_15m",
    "water_level_lag_30m",
    "water_level_change_5m",
    "rainfall_mm_5m",
    "rainfall_mm_15m",
    "rainfall_mm_60m",
    "tide_level_cm",
]
X = df[feature_cols].copy()
X["drainage_restricted"] = (df["drainage_status"] == "restricted").astype(int)
y = df["water_level_future_30m"]

split = int(len(df) * 0.8)
X_train, X_test = X.iloc[:split], X.iloc[split:]
y_train, y_test = y.iloc[:split], y.iloc[split:]

# ------------------------- 8. Random Forest -------------------------------
model = RandomForestRegressor(
    n_estimators=200,
    min_samples_leaf=3,
    random_state=RANDOM_SEED,
    n_jobs=-1,
)
model.fit(X_train, y_train)
pred_rf = model.predict(X_test)

# Baseline: predict the water level 30 minutes ahead using the current level.
pred_baseline = X_test["water_level_cm"].to_numpy()


def evaluate(name, y_true, y_pred):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    print(f"{name:<28} MAE = {mae:.3f} cm | RMSE = {rmse:.3f} cm")


print("\n" + "=" * 70)
print("KẾT QUẢ DỰ BÁO (80% đầu train, 20% cuối test)")
print("=" * 70)
print(f"Train: {len(X_train)} dòng | Test: {len(X_test)} dòng")
evaluate("Random Forest", y_test, pred_rf)
evaluate("Baseline (mực nước hiện tại)", y_test, pred_baseline)

mae_rf = mean_absolute_error(y_test, pred_rf)
mae_base = mean_absolute_error(y_test, pred_baseline)
print(f"\nMAE giảm so với baseline: {(1 - mae_rf / mae_base) * 100:.1f}%")

importance = pd.Series(model.feature_importances_, index=X.columns)
print("\nMức độ quan trọng của các feature (top 5):")
print(importance.sort_values(ascending=False).head(5).round(3).to_string())
